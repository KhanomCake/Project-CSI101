// ใช้ในไฟล์ details/*.js เพื่อเติมข้อมูลละเอียดให้สายพันธุ์ตาม id
// (แยกไฟล์ไว้เพราะข้อมูลละเอียดยาวมาก หน้ารายชื่อสายพันธุ์จะได้ไม่ต้องโหลด)
function addBreedDetails(id, details) {
  const dog = BREEDS.find(function (d) {
    return d.id === id;
  });
  if (dog) {
    Object.assign(dog, details);
  } else {
    console.warn("addBreedDetails: ไม่พบสายพันธุ์ id =", id);
  }
}
