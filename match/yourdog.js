let currentSelectedDog = null;

// ฟังก์ชันค้นหาข้อมูลสุนัข
function findDogBreed(query) {
    const cleanQuery = query.trim().toLowerCase();
    if (!cleanQuery) return null;

    return dogDatabase.find(dog => 
        dog.nameTh.toLowerCase().includes(cleanQuery) ||
        dog.nameEn.toLowerCase().includes(cleanQuery) ||
        dog.keywords.some(kw => kw.toLowerCase().includes(cleanQuery))
    );
}

// ฟังก์ชันแสดงผลข้อมูลบนหน้าเว็บ
function displayDogInfo(dog) {
    currentSelectedDog = dog;
    notFoundAlert.classList.add('hidden');
    resultSection.classList.remove('hidden');

    // ข้อมูลส่วนหัวและสถิติ
    document.getElementById('breedCategory').textContent = dog.category;
    document.getElementById('breedNameTh').textContent = dog.nameTh;
    document.getElementById('breedNameEn').textContent = dog.nameEn;

    // ดึงรูปภาพจาก dog.image ในฐานข้อมูล แล้วแสดงบนหน้าเว็บ
    const breedImage = document.getElementById('breedImage');
    breedImage.src = dog.image || '';
    breedImage.alt = dog.nameEn ? `รูปภาพสุนัขสายพันธุ์ ${dog.nameEn}` : 'รูปภาพสุนัข';
    breedImage.parentElement.style.display = dog.image ? 'block' : 'none';

    document.getElementById('breedWeight').textContent = dog.weight;
    document.getElementById('breedLifespan').textContent = dog.lifespan;
    

    

    // รายละเอียดนิสัยและการดูแลขน
    document.getElementById('breedTemperament').textContent = dog.temperament;
    document.getElementById('breedGrooming').textContent = dog.grooming;

    // รายการโรคประจำพันธุ์
    const healthList = document.getElementById('breedHealth');
    healthList.innerHTML = '';
    dog.health.forEach(item => {
        const li = document.createElement('li');
        li.textContent = item;
        healthList.appendChild(li);
    });

    // รายการเช็กลิสต์ของใช้
    const checkList = document.getElementById('breedChecklist');
    checkList.innerHTML = '';
    dog.checklist.forEach(item => {
        const li = document.createElement('li');
        li.textContent = item;
        checkList.appendChild(li);
    });

    // เลื่อนหน้าจอลงมาที่ผลลัพธ์อย่างนุ่มนวล
    resultSection.scrollIntoView({ behavior: 'smooth', block: 'nearest' });
}



// จัดการเมื่อกดปุ่มค้นหาหรือกด Enter
searchForm.addEventListener('submit', (e) => {
    e.preventDefault();
    autocompleteList.classList.add('hidden');
    const query = breedInput.value;
    const foundDog = findDogBreed(query);

    if (foundDog) {
        displayDogInfo(foundDog);
    } else {
        resultSection.classList.add('hidden');
        searchedTermSpan.textContent = query;
        notFoundAlert.classList.remove('hidden');
    }
});

// ระบบแนะนำคำค้นหาอัตโนมัติ (Autocomplete)
breedInput.addEventListener('input', () => {
    const query = breedInput.value.trim().toLowerCase();
    autocompleteList.innerHTML = '';

    if (!query) {
        autocompleteList.classList.add('hidden');
        return;
    }

    const matches = dogDatabase.filter(dog => 
        dog.nameTh.toLowerCase().includes(query) ||
        dog.nameEn.toLowerCase().includes(query) ||
        dog.keywords.some(kw => kw.toLowerCase().includes(query))
    );

    if (matches.length > 0) {
        matches.forEach(dog => {
            const li = document.createElement('li');
            li.innerHTML = `<span>${dog.nameTh}</span> <small>${dog.nameEn}</small>`;
            li.addEventListener('click', () => {
                breedInput.value = dog.nameTh;
                autocompleteList.classList.add('hidden');
                displayDogInfo(dog);
            });
            autocompleteList.appendChild(li);
        });
        autocompleteList.classList.remove('hidden');
    } else {
        autocompleteList.classList.add('hidden');
    }
});

// ปิด Autocomplete เมื่อคลิกพื้นที่อื่นบนหน้าเว็บ
document.addEventListener('click', (e) => {
    if (!e.target.closest('.search-box-wrapper')) {
        autocompleteList.classList.add('hidden');
    }
});